    private void jButtonDespedirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButtonDespedirActionPerformed
        String nombreSeleccionado = (String) jComboBoxEmployees.getSelectedItem();

        if (nombreSeleccionado == null || nombreSeleccionado.equals("No hay visitantes disponibles")) {
            return;
        }

        Visitante empleadoAEliminar = null;
        for (Visitante empleado : ZooData.zoo.getVisitantes()) {
            if (empleado.getNombre().equals(nombreSeleccionado)) {
                empleadoAEliminar = empleado;
                break;
            }
        }
        
        if (empleadoAEliminar != null) {
            ZooData.zoo.getVisitantes().remove(empleadoAEliminar);
        }

        setup();
    }//GEN-LAST:event_jButtonDespedirActionPerformed


    private void cargarEmpleados(ArrayList<Empleado> empleados) {
        StringBuilder sb = new StringBuilder();
        for (Empleado e : empleados) {
            sb.append("Nombre: ").append(e.getNombre()).append("\n");
            sb.append("ID: ").append(e.getId()).append("\n");
            sb.append("Fecha de ingreso: ").append(e.getFecha()).append("\n");
            sb.append("Sueldo: ").append(e.getSueldo()).append("€\n");
            sb.append("-------------------------\n");
        }
        jTextAreaEmpleados.setText(sb.toString());
    }

